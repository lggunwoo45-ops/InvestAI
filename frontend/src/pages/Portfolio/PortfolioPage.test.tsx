import { DisplayModeProvider } from '@/app/displayMode/DisplayModeProvider'
import { fireEvent, render, screen, within, waitFor } from '@testing-library/react'
import { MemoryRouter } from 'react-router-dom'
import { afterEach, beforeEach, describe, expect, it, vi } from 'vitest'
import { PortfolioPage } from './PortfolioPage'
import { PORTFOLIO_KEY, readPortfolio, writePortfolio } from '@/services/portfolio/portfolioStorage'
import { calculateLedger } from '@/services/portfolio/tradeLedger'
import { createPortfolioBackup } from '@/services/portfolio/portfolioBackup'

const state = vi.hoisted(() => ({ unavailable: false }))
vi.mock('@/i18n/useLanguage', () => ({ useLanguage: () => ({ language: 'en' }) }))
vi.mock('@/hooks/useMarketWorkspace', () => ({ useMarketWorkspace: () => ({ marketDataMode: 'mock' }) }))
vi.mock('@/hooks/useMarketCatalog', () => ({ useMarketCatalog: (venue: string) => ({ loading: false, error: state.unavailable ? 'offline' : null, catalog: state.unavailable ? null : { source: 'mock', fetchedAt: 1000, instruments: [{ id: `${venue}-btc`, marketId: venue.startsWith('upbit') ? 'upbit' : 'binance-spot', symbol: 'BTC', name: 'Bitcoin', quoteCurrency: venue === 'upbit-btc' ? 'BTC' : venue === 'upbit-krw' ? 'KRW' : 'USDT', lastPrice: 125 }] } }) }))
const show = () => render(<MemoryRouter><DisplayModeProvider><PortfolioPage /></DisplayModeProvider></MemoryRouter>)
const add = () => {
  fireEvent.change(screen.getByLabelText('Instrument · quote currency'), { target: { value: 'upbit-krw-btc' } })
  fireEvent.change(screen.getByLabelText('Average price'), { target: { value: '100' } })
  fireEvent.change(screen.getByLabelText('Quantity'), { target: { value: '2' } })
  fireEvent.click(screen.getByRole('button', { name: 'Save' }))
}
describe('My Coins workflow', () => {
  beforeEach(() => { localStorage.clear(); state.unavailable = false })
  afterEach(() => vi.restoreAllMocks())
  it('rejects zero inputs and never shows success after quota failure', () => {
    show()
    fireEvent.change(screen.getByLabelText('Instrument · quote currency'), { target: { value: 'upbit-krw-btc' } })
    fireEvent.change(screen.getByLabelText('Average price'), { target: { value: '0' } })
    fireEvent.change(screen.getByLabelText('Quantity'), { target: { value: '2' } })
    fireEvent.click(screen.getByRole('button', { name: 'Save' }))
    expect(readPortfolio().positions).toHaveLength(0)
    vi.spyOn(Storage.prototype, 'setItem').mockImplementation(() => { throw new Error('quota') })
    add()
    expect(screen.getByText(/Change failed/)).toBeTruthy()
    expect(screen.queryByText('Saved.')).toBeNull()
    expect(readPortfolio().positions).toHaveLength(0)
  })
  it('syncs another tab and cancels an outdated edit', () => {
    show(); add()
    fireEvent.click(screen.getByRole('button', { name: 'Edit' }))
    const current = readPortfolio()
    writePortfolio([], current.raw)
    fireEvent(window, new StorageEvent('storage', { key: PORTFOLIO_KEY }))
    expect(screen.getByText('No saved coins.')).toBeTruthy()
    expect(screen.queryByRole('button', { name: 'Cancel' })).toBeNull()
  })
  it('adds, reloads, edits, confirms deletion, and links a saved position to analysis', () => {
    const view = show()
    add()
    const id = readPortfolio().positions[0].id
    expect(screen.getByText('50 KRW')).toBeTruthy()
    expect(within(screen.getByRole('article')).getByText('25%')).toBeTruthy()
    expect(screen.getAllByText(/Mock quote/).length).toBeGreaterThan(0)
    expect(screen.getByRole('link', { name: 'Analyze this holding →' }).getAttribute('href')).toContain(`positionId=${id}`)
    view.unmount(); show()
    fireEvent.click(screen.getByRole('button', { name: 'Edit' }))
    fireEvent.change(screen.getByLabelText('Quantity'), { target: { value: '3' } })
    fireEvent.click(screen.getByRole('button', { name: 'Save' }))
    expect(readPortfolio().positions[0].quantity).toBe(3)
    fireEvent.click(screen.getByRole('button', { name: 'Delete' }))
    expect(readPortfolio().positions).toHaveLength(1)
    fireEvent.click(within(screen.getByRole('group', { name: 'Delete this position?' })).getByRole('button', { name: 'Delete' }))
    expect(readPortfolio().positions).toHaveLength(0)
  })
  it('retains holdings but suppresses valuation when quotes fail', () => {
    writePortfolio([{ id: '1', exchange: 'upbit', venue: 'upbit-krw', instrumentId: 'upbit-krw-btc', symbol: 'BTC', quoteCurrency: 'KRW', averagePrice: 100, quantity: 2 }], null)
    state.unavailable = true
    show()
    expect(screen.getByRole('heading', { name: 'BTC' })).toBeTruthy()
    expect(within(screen.getByRole('region', { name: 'Investment overview KRW' })).getByText(/Some quotes are missing/)).toBeTruthy()
    expect(screen.queryByText('25%')).toBeNull()
  })
  it('blocks malformed storage without replacing it', () => {
    localStorage.setItem(PORTFOLIO_KEY, 'broken')
    show()
    expect(screen.getByRole('alert')).toBeTruthy()
    expect((screen.getByRole('button', { name: 'Save' }) as HTMLButtonElement).disabled).toBe(true)
    expect(localStorage.getItem(PORTFOLIO_KEY)).toBe('broken')
  })
  it('records buys and sells, previews the result, keeps a closed holding and undoes the last trade', () => {
    show(); add()
    if (!screen.getByText('Manage trades and price targets').closest('details')?.open) fireEvent.click(screen.getByText('Manage trades and price targets'))
    fireEvent.click(screen.getByRole('button', { name: 'Add trade' }))
    fireEvent.change(screen.getByLabelText('Execution price (KRW)'), { target: { value: '200' } })
    fireEvent.change(screen.getByLabelText('Trade quantity'), { target: { value: '2' } })
    expect(screen.getByText('Average after trade')).toBeTruthy()
    expect(readPortfolio().positions[0].quantity).toBe(2)
    fireEvent.click(screen.getByRole('button', { name: 'Save trade' }))
    expect(readPortfolio().positions[0]).toMatchObject({ quantity: 4, averagePrice: 150 })
    fireEvent.click(screen.getByRole('button', { name: 'Edit' }))
    expect((screen.getByLabelText('Average price') as HTMLInputElement).readOnly).toBe(true)
    fireEvent.click(screen.getByRole('button', { name: 'Cancel' }))
    if (!screen.getByText('Manage trades and price targets').closest('details')?.open) fireEvent.click(screen.getByText('Manage trades and price targets'))
    fireEvent.click(screen.getByRole('button', { name: 'Add trade' }))
    fireEvent.change(screen.getByLabelText('Trade side'), { target: { value: 'sell' } })
    fireEvent.change(screen.getByLabelText('Execution price (KRW)'), { target: { value: '180' } })
    fireEvent.change(screen.getByLabelText('Trade quantity'), { target: { value: '5' } })
    expect(screen.getByText(/Cannot sell more/)).toBeTruthy()
    expect((screen.getByRole('button', { name: 'Save trade' }) as HTMLButtonElement).disabled).toBe(true)
    fireEvent.change(screen.getByLabelText('Trade quantity'), { target: { value: '4' } })
    fireEvent.click(screen.getByRole('button', { name: 'Save trade' }))
    const closed = readPortfolio().positions[0]
    expect(closed.quantity).toBe(0)
    expect(calculateLedger(closed.ledger).realized).toBe(120)
    expect(screen.getByText('Closed holding')).toBeTruthy()
    expect(screen.queryByRole('region', { name: 'Investment overview KRW' })).toBeNull()
    expect(screen.queryByRole('link', { name: 'Analyze this holding →' })).toBeNull()
    fireEvent.click(screen.getByText(/View trade history/))
    fireEvent.click(screen.getByRole('button', { name: 'Undo last trade' }))
    expect(readPortfolio().positions[0].quantity).toBe(0)
    const confirm = screen.getByRole('group', { name: 'Undo the last trade and restore the preceding balance?' })
    fireEvent.click(within(confirm).getByRole('button', { name: 'Undo last trade' }))
    expect(readPortfolio().positions[0].quantity).toBe(4)
  })
  it('previews a backup before additive restore and prevents duplicate restoration', async () => {
    show(); add()
    fireEvent.click(screen.getByText('Backup and storage'))
    const existing = readPortfolio()
    const extra = { ...existing.positions[0], id: 'restored', symbol: 'Restored BTC' }
    const text = createPortfolioBackup({ positions: [extra], raw: null, error: null })
    const file = new File([text], 'backup.json', { type: 'application/json' })
    Object.defineProperty(file, 'text', { value: async () => text })
    fireEvent.change(screen.getByLabelText('Choose backup file'), { target: { files: [file] } })
    await screen.findByRole('region', { name: 'Restore preview' })
    expect(readPortfolio().positions).toHaveLength(1)
    fireEvent.click(screen.getByRole('button', { name: 'Confirm additive restore' }))
    expect(readPortfolio().positions).toHaveLength(2)
    fireEvent.change(screen.getByLabelText('Choose backup file'), { target: { files: [file] } })
    await screen.findByRole('region', { name: 'Restore preview' })
    expect((screen.getByRole('button', { name: 'Confirm additive restore' }) as HTMLButtonElement).disabled).toBe(true)
  })
  it('rejects conflicting backups without changing stored holdings', async () => {
    show(); add()
    fireEvent.click(screen.getByText('Backup and storage'))
    const existing = readPortfolio()
    const text = createPortfolioBackup({ ...existing, positions: [{ ...existing.positions[0], quantity: 9 }] })
    const file = new File([text], 'conflict.json')
    Object.defineProperty(file, 'text', { value: async () => text })
    fireEvent.change(screen.getByLabelText('Choose backup file'), { target: { files: [file] } })
    await screen.findByText(/Cannot restore/)
    expect(readPortfolio().raw).toBe(existing.raw)
    expect(screen.queryByRole('region', { name: 'Restore preview' })).toBeNull()
  })
  it('cancels a pending import if another tab changes the portfolio', async () => {
    show(); add()
    fireEvent.click(screen.getByText('Backup and storage'))
    const existing = readPortfolio()
    let finish: (text: string) => void = () => undefined
    const file = new File(['pending'], 'backup.json')
    Object.defineProperty(file, 'text', { value: () => new Promise<string>(resolve => { finish = resolve }) })
    fireEvent.change(screen.getByLabelText('Choose backup file'), { target: { files: [file] } })
    writePortfolio([], existing.raw)
    fireEvent(window, new StorageEvent('storage', { key: PORTFOLIO_KEY }))
    finish(createPortfolioBackup(existing))
    await waitFor(() => expect(screen.queryByText('Checking file')).toBeNull())
    expect(screen.queryByRole('region', { name: 'Restore preview' })).toBeNull()
    expect(readPortfolio().positions).toHaveLength(0)
  })
  it('saves a plan, rejects inverted thresholds and lets users clear their criteria', () => {
    show()
    fireEvent.change(screen.getByLabelText('Target price (optional)'), { target: { value: '120' } })
    fireEvent.change(screen.getByLabelText('Stop reference price (optional)'), { target: { value: '80' } })
    add()
    expect(readPortfolio().positions[0]).toMatchObject({ targetPrice: 120, stopPrice: 80 })
    expect(screen.getByText('Threshold reached')).toBeTruthy()
    fireEvent.click(screen.getByRole('button', { name: 'Edit' }))
    fireEvent.change(screen.getByLabelText('Stop reference price (optional)'), { target: { value: '130' } })
    fireEvent.click(screen.getByRole('button', { name: 'Save' }))
    expect(screen.getByText(/Target and stop must be valid/)).toBeTruthy()
    expect(readPortfolio().positions[0].stopPrice).toBe(80)
    fireEvent.change(screen.getByLabelText('Stop reference price (optional)'), { target: { value: '' } })
    fireEvent.change(screen.getByLabelText('Target price (optional)'), { target: { value: '' } })
    fireEvent.click(screen.getByRole('button', { name: 'Save' }))
    expect(readPortfolio().positions[0].targetPrice).toBeUndefined()
    expect(screen.queryByText('Threshold reached')).toBeNull()
  })
  it('shows saved criteria without a reached signal when a quote is unavailable', () => {
    writePortfolio([{ id: '1', exchange: 'upbit', venue: 'upbit-krw', instrumentId: 'upbit-krw-btc', symbol: 'BTC', quoteCurrency: 'KRW', averagePrice: 100, quantity: 2, targetPrice: 120, stopPrice: 80 }], null)
    state.unavailable = true
    show()
    expect(screen.getAllByText('Quote needed')).toHaveLength(2)
    expect(screen.getByText('120 KRW')).toBeTruthy()
    expect(screen.queryByText('Threshold reached')).toBeNull()
  })
  it('clears stale plan inputs after another tab edits the holding', () => {
    show(); add()
    fireEvent.click(screen.getByRole('button', { name: 'Edit' }))
    fireEvent.change(screen.getByLabelText('Target price (optional)'), { target: { value: '200' } })
    const current = readPortfolio()
    writePortfolio([{ ...current.positions[0], targetPrice: 150 }], current.raw)
    fireEvent(window, new StorageEvent('storage', { key: PORTFOLIO_KEY }))
    expect((screen.getByLabelText('Target price (optional)') as HTMLInputElement).value).toBe('')
    expect(screen.getByText('150 KRW')).toBeTruthy()
    expect(screen.queryByRole('button', { name: 'Cancel' })).toBeNull()
  })
})
